//! The Vorbis headers Warframe's Vorbis sounds are missing.
//!
//! A Vorbis stream starts with three header packets: identification, comment and setup
//! (the codebooks, a few kilobytes). The game stores only the audio packets of each
//! sound and keeps a handful of header sets in its executable, one per combination of
//! channel count, sample rate and encoder quality.
//!
//! Those sets are exactly what libvorbis 1.3.7 writes for `vorbis_encode_init_vbr` at
//! qualities -0.1 and 0.45 (32 kHz) and 0.725, 0.78, 0.835 and 0.89 (44.1 kHz), mono and
//! stereo: all three packets of all 12 sets, byte for byte. So wfscan bundles the sets
//! as generated by libvorbis (`data/vorbis_headers.bin`, made by `tools/vorbis-headers`,
//! under libvorbis's BSD license in `data/COPYING-libvorbis`) and needs nothing from the
//! game. [`VorbisTables::scan`] still reads the sets out of an executable, to check the
//! bundled ones against a new game version or to pick up a set the game has added.
//!
//! In the executable each set is three packets in a row, each followed (after padding to
//! 8 bytes) by a record of a pointer, the packet's length as a u32 and a u32 of 1.
//!
//! The 12 sets hold 8 distinct setups. For 32 kHz there is one per channel count with
//! the block sizes the sounds use (256 and 2048). For 44.1 kHz there are two per channel
//! count (qualities 0.725/0.78 share one, 0.835/0.89 the other), and nothing found in a
//! sound's header says which it was encoded with: most sounds use the second, some the
//! first. A sound decoded with the wrong one is noise, so [`super::decode`] tries both
//! and keeps the cleaner result.
//!
//! Source: the September 2026 `Warframe.x64.exe` and cache, and libvorbis 1.3.7. The
//! original exporter doesn't read these sounds (it lists codecs 0, 5 and 7 only).

use std::path::{Path, PathBuf};
use std::sync::OnceLock;

/// How far after a setup packet's start its length record can be.
const MAX_SETUP: usize = 64 << 10;

/// One set of Vorbis header packets.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct VorbisHeaders {
    pub channels: u8,
    pub sample_rate: u32,
    /// The nominal bitrate the identification packet states.
    pub bitrate: i32,
    /// Samples in a short and a long block.
    pub block_sizes: (u32, u32),
    pub ident: Vec<u8>,
    pub comment: Vec<u8>,
    pub setup: Vec<u8>,
}

/// The sets generated by `tools/vorbis-headers`: `WFVORBIS`, a u32 count, then per set
/// the encoder quality x 1000 as an i32 and the three packets, each behind a u32 length.
static BUNDLED: &[u8] = include_bytes!("../../../data/vorbis_headers.bin");

/// A collection of header sets: the bundled ones, or those found in a game executable.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct VorbisTables {
    pub sets: Vec<VorbisHeaders>,
}

fn u32_at(data: &[u8], at: usize) -> Option<u32> {
    Some(u32::from_le_bytes(*data.get(at..)?.first_chunk()?))
}

fn find(data: &[u8], needle: &[u8]) -> Option<usize> {
    data.windows(needle.len()).position(|w| w == needle)
}

/// The length of the packet starting at `start`, from the record after it.
fn packet_len(data: &[u8], start: usize, max: usize) -> Option<usize> {
    let mut record = start.next_multiple_of(8);
    while record < start + max {
        let len = u32_at(data, record + 8)? as usize;
        if len >= 8 && start + len <= record && record - (start + len) < 8 && u32_at(data, record + 12)? == 1 {
            return Some(len);
        }
        record += 8;
    }
    None
}

impl VorbisHeaders {
    /// A set from its three packets; `None` if the identification packet isn't one.
    pub fn from_packets(ident: &[u8], comment: &[u8], setup: &[u8]) -> Option<Self> {
        // The packet type and name, version 0, and the framing bit.
        if ident.len() != 30 || &ident[..7] != b"\x01vorbis" || ident[7..11] != [0; 4] || ident[29] != 1 {
            return None;
        }
        let (short, long) = (ident[28] & 15, ident[28] >> 4);
        if ident[11] == 0 || u32_at(ident, 12)? == 0 || !(6..=13).contains(&short) || !(6..=13).contains(&long) || short > long {
            return None;
        }
        // The first codebook's sync pattern follows the codebook count.
        if !comment.starts_with(b"\x03vorbis") || !setup.starts_with(b"\x05vorbis") || setup.get(8..11)? != b"BCV" {
            return None;
        }
        Some(Self {
            channels: ident[11],
            sample_rate: u32_at(ident, 12)?,
            bitrate: u32_at(ident, 20)? as i32,
            block_sizes: (1 << short, 1 << long),
            ident: ident.to_vec(),
            comment: comment.to_vec(),
            setup: setup.to_vec(),
        })
    }
}

impl VorbisTables {
    /// The sets wfscan ships, generated by libvorbis 1.3.7.
    pub fn bundled() -> &'static Self {
        static TABLES: OnceLock<VorbisTables> = OnceLock::new();
        TABLES.get_or_init(|| Self::parse_bundled(BUNDLED).expect("the bundled Vorbis header file is well formed"))
    }

    fn parse_bundled(data: &[u8]) -> Option<Self> {
        let mut at = 12;
        let count = u32_at(data.strip_prefix(b"WFVORBIS")?, 0)?;
        let mut sets = Vec::new();
        for _ in 0..count {
            // The quality is for people reading the file.
            at += 4;
            let mut packets = [&data[..0]; 3];
            for packet in &mut packets {
                let len = u32_at(data, at)? as usize;
                *packet = data.get(at + 4..at + 4 + len)?;
                at += 4 + len;
            }
            sets.push(VorbisHeaders::from_packets(packets[0], packets[1], packets[2])?);
        }
        (at == data.len()).then_some(Self { sets })
    }

    /// These sets followed by the ones of `other` that aren't among them.
    pub fn with(mut self, other: &Self) -> Self {
        for set in &other.sets {
            if !self.sets.contains(set) {
                self.sets.push(set.clone());
            }
        }
        self
    }

    /// Find every header set in the bytes of an executable.
    pub fn scan(data: &[u8]) -> Self {
        let mut sets = Vec::new();
        let mut at = 0;
        while let Some(found) = find(&data[at..], b"\x01vorbis") {
            let ident_at = at + found;
            at = ident_at + 7;
            if let Some(set) = set_at(data, ident_at) {
                sets.push(set);
            }
        }
        Self { sets }
    }

    pub fn load(exe: &Path) -> std::io::Result<Self> {
        Ok(Self::scan(&std::fs::read(exe)?))
    }

    /// The game's executable for a cache folder: an `.exe` next to `Cache.Windows`, the
    /// largest if there are several (the launcher and crash reporter are small).
    pub fn find_exe(cache_dir: &Path) -> Option<PathBuf> {
        let game_dir = cache_dir.parent()?;
        let exes = std::fs::read_dir(game_dir).ok()?.filter_map(|entry| {
            let entry = entry.ok()?;
            let path = entry.path();
            let is_exe = path.extension().is_some_and(|x| x.eq_ignore_ascii_case("exe"));
            is_exe.then_some(())?;
            Some((entry.metadata().ok()?.len(), path))
        });
        exes.max_by_key(|(size, _)| *size).map(|(_, path)| path)
    }

    /// The sets a sound with these properties could have been encoded with, in the
    /// executable's order, without repeats of the same setup.
    pub fn candidates(&self, channels: u8, sample_rate: u32, long_block: u32) -> Vec<&VorbisHeaders> {
        let mut out: Vec<&VorbisHeaders> = Vec::new();
        for set in &self.sets {
            if set.channels == channels && set.sample_rate == sample_rate && set.block_sizes.1 == long_block && !out.iter().any(|o| o.setup == set.setup) {
                out.push(set);
            }
        }
        out
    }
}

/// The set whose identification packet starts at `ident_at`, if the three packets and
/// their length records are all there.
fn set_at(data: &[u8], ident_at: usize) -> Option<VorbisHeaders> {
    let ident = data.get(ident_at..ident_at + 30)?;
    if packet_len(data, ident_at, 64)? != 30 {
        return None;
    }
    let comment_at = ident_at + 30 + find(data.get(ident_at + 30..ident_at + 256)?, b"\x03vorbis")?;
    let comment_len = packet_len(data, comment_at, 4096)?;
    let after = comment_at + comment_len;
    let setup_at = after + find(data.get(after..after + 256)?, b"\x05vorbis")?;
    let setup_len = packet_len(data, setup_at, MAX_SETUP)?;
    VorbisHeaders::from_packets(ident, &data[comment_at..after], data.get(setup_at..setup_at + setup_len)?)
}

#[cfg(test)]
mod tests {
    use super::*;

    /// A packet as the executable holds it: padded to 8 bytes, then its record.
    fn stored(out: &mut Vec<u8>, packet: &[u8]) {
        out.extend_from_slice(packet);
        out.resize(out.len().next_multiple_of(8), 0);
        out.extend_from_slice(&[0xaa; 8]);
        out.extend_from_slice(&(packet.len() as u32).to_le_bytes());
        out.extend_from_slice(&1u32.to_le_bytes());
        out.extend_from_slice(&[0; 24]);
    }

    fn set(out: &mut Vec<u8>, channels: u8, rate: u32, bitrate: i32, blocks: u8, setup_fill: u8) {
        let mut ident = b"\x01vorbis\0\0\0\0".to_vec();
        ident.push(channels);
        ident.extend_from_slice(&rate.to_le_bytes());
        ident.extend_from_slice(&0i32.to_le_bytes());
        ident.extend_from_slice(&bitrate.to_le_bytes());
        ident.extend_from_slice(&0i32.to_le_bytes());
        ident.extend_from_slice(&[blocks, 1]);
        stored(out, &ident);
        stored(out, b"\x03vorbis\x04\0\0\0test\0\0\0\0\x01");
        let mut setup = b"\x05vorbis\x01BCV".to_vec();
        setup.extend_from_slice(&[setup_fill; 300]);
        stored(out, &setup);
    }

    #[test]
    fn sets_are_found_in_an_executable() {
        let mut exe = vec![0x90; 64];
        set(&mut exe, 1, 44100, 125_000, 0xb8, 1);
        exe.extend_from_slice(b"\x01vorbis is also a word in some string");
        set(&mut exe, 2, 44100, 232_000, 0xb8, 2);
        set(&mut exe, 1, 44100, 136_000, 0xb8, 1);
        set(&mut exe, 1, 44100, 147_000, 0xb8, 3);
        set(&mut exe, 1, 32000, 30_000, 0xc9, 4);
        let tables = VorbisTables::scan(&exe);
        assert_eq!(tables.sets.iter().map(|s| s.bitrate).collect::<Vec<_>>(), [125_000, 232_000, 136_000, 147_000, 30_000]);
        let first = &tables.sets[0];
        assert_eq!((first.channels, first.sample_rate, first.block_sizes), (1, 44100, (256, 2048)));
        assert_eq!((first.ident.len(), first.comment.len(), first.setup.len()), (30, 20, 311));
        assert_eq!(tables.sets[4].block_sizes, (512, 4096));

        // Same channels, rate and long block; the repeated setup is listed once.
        let mono: Vec<i32> = tables.candidates(1, 44100, 2048).iter().map(|s| s.bitrate).collect();
        assert_eq!(mono, [125_000, 147_000]);
        assert!(tables.candidates(1, 32000, 2048).is_empty() && tables.candidates(2, 48000, 2048).is_empty());
        assert!(VorbisTables::scan(b"no vorbis here").sets.is_empty());
    }

    #[test]
    fn the_bundled_sets_are_the_games_twelve() {
        let tables = VorbisTables::bundled();
        let sets: Vec<(u8, u32, i32, u32)> = tables.sets.iter().map(|s| (s.channels, s.sample_rate, s.bitrate, s.block_sizes.1)).collect();
        #[rustfmt::skip]
        assert_eq!(sets, [
            (1, 32000, 30_000, 4096), (2, 32000, 36_000, 4096), (1, 32000, 82_000, 2048), (2, 32000, 135_000, 2048),
            (1, 44100, 125_000, 2048), (2, 44100, 232_000, 2048), (1, 44100, 136_000, 2048), (2, 44100, 249_600, 2048),
            (1, 44100, 147_000, 2048), (2, 44100, 278_400, 2048), (1, 44100, 158_000, 2048), (2, 44100, 313_600, 2048),
        ]);
        // The encoder names itself in every comment packet.
        assert!(tables.sets.iter().all(|s| s.comment.windows(29).any(|w| w == b"Xiph.Org libVorbis I 20200704")));
        // One setup for 32 kHz sounds, two to choose between at 44.1 kHz.
        assert_eq!(tables.candidates(1, 32000, 2048).len(), 1);
        assert_eq!(tables.candidates(2, 44100, 2048).iter().map(|s| s.bitrate).collect::<Vec<_>>(), [232_000, 278_400]);
        assert_eq!(BUNDLED.len(), 46_137);
        assert!(VorbisTables::parse_bundled(&BUNDLED[..BUNDLED.len() - 1]).is_none() && VorbisTables::parse_bundled(b"WFVORBIS").is_none());
    }

    #[test]
    fn sets_from_elsewhere_are_added_once() {
        let mut exe = Vec::new();
        set(&mut exe, 1, 48000, 99_000, 0xb8, 9);
        let found = VorbisTables::scan(&exe);
        let merged = VorbisTables::bundled().clone().with(&found).with(&found).with(VorbisTables::bundled());
        assert_eq!(merged.sets.len(), 13);
        assert_eq!(merged.candidates(1, 48000, 2048).len(), 1);
    }

    #[test]
    fn the_largest_exe_next_to_the_cache_is_the_game() {
        let dir = tempfile::tempdir().unwrap();
        let cache = dir.path().join("Cache.Windows");
        std::fs::create_dir(&cache).unwrap();
        assert_eq!(VorbisTables::find_exe(&cache), None);
        std::fs::write(dir.path().join("Launcher.exe"), [0; 10]).unwrap();
        std::fs::write(dir.path().join("Game.x64.EXE"), [0; 100]).unwrap();
        std::fs::write(dir.path().join("big.dat"), [0; 1000]).unwrap();
        assert_eq!(VorbisTables::find_exe(&cache), Some(dir.path().join("Game.x64.EXE")));
    }
}
